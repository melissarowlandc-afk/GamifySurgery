import { act } from "react";
import { afterEach, describe, expect, it, vi } from "vitest";
import { createInitialGameState } from "@gamify-surgery/game-domain";
import { createPrototypePlayerView } from "../../session/viewModels";
import type { FacilityCanvasProps } from "../../facility";
import { clampFacilityCamera } from "../../facility/facilityCameraBounds";
import { writeFacilityCameraPreference, facilityCameraPreferenceKey } from "../../session/facilityCameraPreference";
import { TestDocument, TestElement, findTestElement, testElementProps } from "../testDom";
import { MobileFacilityMap } from "./MobileFacilityMap";
import { createPhoneCameraPreferenceSession, phoneCameraPreferenceKey, readPhoneCameraPreference } from "./cameraPreference";
const capture = vi.hoisted(() => ({ props: null as FacilityCanvasProps | null }));
vi.mock("../../facility", () => ({ FacilityCanvas: (props: FacilityCanvasProps) => { capture.props = props; return <div>Map fixture</div>; } }));
afterEach(() => { vi.unstubAllGlobals(); capture.props = null; });

describe("phone-only map camera ownership", () => {
  it("passes the explicit flag, frames the visible host, uses phone controls and flushes only phone storage", async () => {
    const doc = new TestDocument(); const element = doc.createElement("div"); doc.body.appendChild(element);
    const values = new Map<string, string>();
    const storage = { getItem: (key: string) => values.get(key) ?? null, setItem: (key: string, value: string) => { values.set(key, value); } };
    const browser = Object.assign(new EventTarget(), { document: doc, localStorage: storage, HTMLElement: TestElement, HTMLIFrameElement: class extends TestElement {} });
    doc.defaultView = browser; vi.stubGlobal("window", browser); vi.stubGlobal("document", doc);
    vi.stubGlobal("HTMLElement", TestElement); vi.stubGlobal("IS_REACT_ACT_ENVIRONMENT", true);
    const { createRoot } = await import("react-dom/client"); const root = createRoot(element as unknown as HTMLElement);
    const model = { ...createPrototypePlayerView(createInitialGameState(), null, false, null).facility, campaignId: "A", camera: { zoom: 0.3, panX: 20, panY: 10 } };
    writeFacilityCameraPreference("A", model.camera, storage); const desktopBytes = storage.getItem(facilityCameraPreferenceKey("A"));
    await act(async () => root.render(<MobileFacilityMap viewModel={model} onPlaceRoom={() => false} onMobileSelection={vi.fn()} />));
    expect(findTestElement(element, node => node.attributes["aria-label"]?.startsWith("Zoom facility") === true)).toBeUndefined();
    expect(findTestElement(element, node => node.tagName === "OUTPUT")).toBeUndefined();
    expect(capture.props?.mobileInput).toBe(true); expect(capture.props?.viewModel.camera?.zoom).toBeGreaterThan(1);
    const framed = capture.props!.viewModel.camera!;
    await act(async () => capture.props!.onCameraChange!({ ...framed, zoom: 1.5 }));
    expect(capture.props!.viewModel.camera!.zoom).toBe(1.5);
    const recenter = findTestElement(element, (node) => node.attributes["aria-label"] === "Recenter facility")!;
    await act(async () => { (testElementProps(recenter).onClick as () => void)(); });
    expect(capture.props!.viewModel.camera).toEqual(framed);
    await act(async () => root.unmount());
    expect(storage.getItem(facilityCameraPreferenceKey("A"))).toBe(desktopBytes);
    expect(storage.getItem(phoneCameraPreferenceKey("A"))).not.toBeNull();
    const reloaded = createRoot(element as unknown as HTMLElement);
    await act(async () => reloaded.render(<MobileFacilityMap viewModel={model} onPlaceRoom={() => false} onMobileSelection={vi.fn()} />));
    expect(capture.props!.viewModel.camera).toEqual(framed);
    await act(async () => reloaded.unmount());
  });
  it.each([{ zoom: 1, panX: 0, panY: -100 }, { zoom: 1, panX: -1e9, panY: 1e9 }])("restores, bounds and saves padded phone pan $panY without touching the desktop entry", async (saved) => {
    const doc = new TestDocument(); const element = doc.createElement("div"); doc.body.appendChild(element);
    const values = new Map<string, string>();
    const storage = { getItem: (key: string) => values.get(key) ?? null, setItem: (key: string, value: string) => { values.set(key, value); } };
    const browser = Object.assign(new EventTarget(), { document: doc, localStorage: storage, HTMLElement: TestElement, HTMLIFrameElement: class extends TestElement {} });
    doc.defaultView = browser; vi.stubGlobal("window", browser); vi.stubGlobal("document", doc);
    vi.stubGlobal("HTMLElement", TestElement); vi.stubGlobal("IS_REACT_ACT_ENVIRONMENT", true);
    const model = { ...createPrototypePlayerView(createInitialGameState(), null, false, null).facility, campaignId: "padded" };
    const size = { width: 390, height: 600 };
    writeFacilityCameraPreference("padded", { zoom: 0.5, panX: 0, panY: 0 }, storage);
    const desktopBytes = storage.getItem(facilityCameraPreferenceKey("padded"));
    const preferences = createPhoneCameraPreferenceSession(storage); preferences.change("padded", saved); preferences.flush();
    const { createRoot } = await import("react-dom/client"); const root = createRoot(element as unknown as HTMLElement);
    await act(async () => root.render(<MobileFacilityMap viewModel={model} onPlaceRoom={() => false} onMobileSelection={vi.fn()} />));
    expect(capture.props!.viewModel.camera).toEqual(clampFacilityCamera(saved, model, size, true));
    expect(capture.props!.viewModel.camera).not.toEqual(clampFacilityCamera(saved, model, size));
    const requested = { zoom: 1.5, panX: 1e9, panY: -1e9 };
    await act(async () => capture.props!.onCameraChange!(requested));
    const expected = clampFacilityCamera(requested, model, size, true);
    expect(capture.props!.viewModel.camera).toEqual(expected);
    await act(async () => root.unmount());
    expect(readPhoneCameraPreference("padded", storage)).toEqual(expected);
    expect(storage.getItem(facilityCameraPreferenceKey("padded"))).toBe(desktopBytes);
  });
});
