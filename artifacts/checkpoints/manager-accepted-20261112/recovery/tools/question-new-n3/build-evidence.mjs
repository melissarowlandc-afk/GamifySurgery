// Offline metadata transformation only. Never fetch articles or infer verification.
import '../economy-audit/source-loader.mjs';
import fs from 'node:fs';
import assert from 'node:assert/strict';
import {createHash} from 'node:crypto';
const a = await import('../../packages/clinical-content/src/question-new-n3-level3.ts');
const b = await import('../../packages/clinical-content/src/question-new-n3-level4.ts');
const items = [...a.QUESTION_NEW_N3_LEVEL3, ...b.QUESTION_NEW_N3_LEVEL4];
const inputPath = '.local-dev/question-new-n2-round3-ship-gate-20261104/recorded-catalog.json';
assert.ok(fs.existsSync(inputPath), 'Requires the recorded offline receipt; do not fetch replacement content.');
const recorded = JSON.parse(fs.readFileSync(inputPath, 'utf8'));
const draft = {contentVersion:'clinical.question-new-n3.2026-11-05.v1',reviewStatus:'needs_clinician_review',aiAssistedDrafting:true,lastClinicianReview:null};
const used = [...new Set(items.flatMap(i => i.existingClaimIds))].sort();
const provenance = [], claims = [];
for (const id of used) {
  assert.ok(!/^claim\.(?:n1|n2|qbp2b|qf[23])/.test(id), 'No held/new peer-lane extension may be used as an inherited key fact.');
  const original = recorded.claims.find(c => c.id === id);
  assert.ok(original, 'Missing recorded claim: '+id);
  const claimId = 'claim.n3.'+createHash('sha256').update(id).digest('hex').slice(0,12);
  claims.push({...original,...draft,id:claimId});
  provenance.push({claimId,inheritedClaimId:id,inheritedContentVersion:original.contentVersion,
    inheritedLastCheckedOn:original.lastCheckedOn,localMappingCheckedOn:'2026-11-05',statementUnchanged:true,
    verificationBasis:'Exact reuse of the previously recorded independently written atomic statement and its original source/check dates; no new retrieval or freshness assertion.'});
}
const sourceIds = new Set(claims.flatMap(c => c.sourceIds));
const sources = recorded.sources.filter(s => sourceIds.has(s.id)).map(s => ({...s,...draft,
  evidenceClaimIds:claims.filter(c => c.sourceIds.includes(s.id)).map(c => c.id)}));
assert.equal(sources.length,sourceIds.size);
for (const s of sources) for (const field of ['completeCitation','organizationOrJournal','accessedOn','sourceClass','licenseLabel','reuseStatus','usageRole','authorityAssessment'])
  assert.ok(s[field], s.id+' '+field);
const body = '// Generated by tools/question-new-n3/build-evidence.mjs from a recorded offline metadata receipt.\n'+
  '// Statements and prior source access/check dates are unchanged; new versions remain unapproved.\n'+
  'import type { ClinicalSource, EvidenceClaim } from "./pilot-schema";\n\n'+
  'export const QUESTION_NEW_N3_CLAIM_PROVENANCE = '+JSON.stringify(provenance,null,2)+' as const;\n\n'+
  'export const QUESTION_NEW_N3_CLAIMS: EvidenceClaim[] = '+JSON.stringify(claims,null,2)+';\n\n'+
  'export const QUESTION_NEW_N3_SOURCES: ClinicalSource[] = '+JSON.stringify(sources,null,2)+';\n';
fs.writeFileSync('packages/clinical-content/src/question-new-n3-evidence-20261105.ts',body);
console.log(JSON.stringify({items:items.length,atomicClaims:claims.length,sources:sources.length,newRetrievals:0}));
