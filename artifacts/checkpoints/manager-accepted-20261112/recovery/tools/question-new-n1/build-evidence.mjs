// Authoring-time reuse only; runtime imports the generated local metadata module.
import '../economy-audit/source-loader.mjs';
import fs from 'node:fs';
import { createHash } from 'node:crypto';
const { QUESTION_NEW_N1_ABDOMINAL } = await import('../../packages/clinical-content/src/question-new-n1-abdominal.ts');
const { QUESTION_NEW_N1_BREAST } = await import('../../packages/clinical-content/src/question-new-n1-breast.ts');
const { QUESTION_NEW_N1_PERIOPERATIVE } = await import('../../packages/clinical-content/src/question-new-n1-perioperative.ts');
const items = [...QUESTION_NEW_N1_ABDOMINAL, ...QUESTION_NEW_N1_BREAST, ...QUESTION_NEW_N1_PERIOPERATIVE];
const catalog = JSON.parse(fs.readFileSync('.local-dev/question-new-content-20261104/catalog-before.json', 'utf8'));
const draft = { contentVersion: 'clinical.question-new-n1.2026-11-04.v1', reviewStatus: 'needs_clinician_review', aiAssistedDrafting: true, lastClinicianReview: null };
const requested = [...new Set(items.flatMap(item => item.existingClaimIds))].sort();
const missing = requested.filter(id => !catalog.claims.some(claim => claim.id === id));
if (missing.length) throw new Error(`Missing recorded claims: ${missing.join(', ')}`);
const inherited = requested.map(id => catalog.claims.find(claim => claim.id === id));
const provenance = inherited.map(claim => ({ claimId: `claim.n1.${createHash('sha256').update(claim.id).digest('hex').slice(0, 12)}`,
  inheritedClaimId: claim.id, inheritedContentVersion: claim.contentVersion, inheritedLastCheckedOn: claim.lastCheckedOn,
  checkedLocallyOn: '2026-11-04', verificationBasis: 'Previously recorded independent repository synthesis; no source newly retrieved.',
  statementUnchanged: true }));
const claims = inherited.map((record, i) => {
  const allowed = new Set(['id', 'contentVersion', 'reviewStatus', 'aiAssistedDrafting', 'lastClinicianReview',
    'statement', 'sourceIds', 'evidenceCategory', 'certainty', 'limitation', 'applicablePopulation', 'lastCheckedOn']);
  const claim = Object.fromEntries(Object.entries(record).filter(([key]) => allowed.has(key)));
  return ({ ...claim, ...draft, id: provenance[i].claimId,
  limitation: [claim.limitation, 'Offline reuse: source verification and currentness have not been refreshed for N1. Exact authored application and option ranking require clinician review.',
    new Set(claim.sourceIds).size === 1 ? 'Only one recorded source supports this atomic claim; no independent management cross-check has been added.' : null].filter(Boolean).join(' ') });
});
const sourceIds = [...new Set(claims.flatMap(claim => claim.sourceIds))].sort();
const missingSources = sourceIds.filter(id => !catalog.sources.some(source => source.id === id));
if (missingSources.length) throw new Error(`Missing recorded sources: ${missingSources.join(', ')}`);
const sources = sourceIds.map(id => {
  const source = catalog.sources.find(source => source.id === id);
  return { ...source, ...draft, evidenceClaimIds: [...new Set([...source.evidenceClaimIds,
    ...claims.filter(claim => claim.sourceIds.includes(id)).map(claim => claim.id)])],
    reuseNotes: `${source.reuseNotes} N1 reuses locally recorded atomic synthesis and bibliographic metadata only; no source text, table, figure or excerpt was retrieved or copied. Access date is inherited; N1 did not refresh it.` };
});
const target = 'packages/clinical-content/src/question-new-n1-evidence-20261104.ts';
fs.writeFileSync(target, '// Generated by tools/question-new-n1/build-evidence.mjs from the captured pre-N1 atomic-claim catalog.\n' +
  '// Original source access and claim check dates remain authoritative. No newly retrieved sources.\n' +
  'import type { ClinicalSource, EvidenceClaim } from "./pilot-schema";\n\n' +
  `export const QUESTION_NEW_N1_CLAIM_PROVENANCE = ${JSON.stringify(provenance, null, 2)} as const;\n\n` +
  `export const QUESTION_NEW_N1_CLAIMS: EvidenceClaim[] = ${JSON.stringify(claims, null, 2)};\n\n` +
  `export const QUESTION_NEW_N1_SOURCES: ClinicalSource[] = ${JSON.stringify(sources, null, 2)};\n`);
console.log(JSON.stringify({ items: items.length, newIdentities: items.filter(item => item.identityBasis === 'new_decision_construct').length,
  preservedUnadmitted: items.filter(item => item.identityBasis === 'preserved_unadmitted_identity').length, claims: claims.length, sources: sources.length, target }, null, 2));
