// Offline metadata reuse. No retrieval, new source verification or clinical approval.
import '../economy-audit/source-loader.mjs';
import fs from 'node:fs';
import assert from 'node:assert/strict';
import {createHash} from 'node:crypto';
const old=await import('../../packages/clinical-content/src/question-new-n3-20261105.ts');
const rows=[];
for(const part of ['level3-nutrition','level3-specialty','level4-oncology','level4-foregut','level4-critical']){
  const m=await import(`../../packages/clinical-content/src/question-new-n3-round2-${part}.ts`);
  rows.push(...Object.values(m).flat());
}
assert.equal(rows.length,39);assert.equal(new Set(rows.map(r=>r.slug)).size,39);
assert.ok(!rows.some(r=>r.slug==='pleural-source-versus-systemic-response'));
const recorded=JSON.parse(fs.readFileSync('.local-dev/question-new-n2-round3-ship-gate-20261104/recorded-catalog.json','utf8'));
const draft={contentVersion:'clinical.question-new-n3.2026-11-05.v2',reviewStatus:'needs_clinician_review',aiAssistedDrafting:true,lastClinicianReview:null};
// Keep every first-round atomic statement/metadata record byte-equivalent.
const claims=[...old.QUESTION_NEW_N3_CLAIMS],provenance=[...old.QUESTION_NEW_N3_CLAIM_PROVENANCE];
for(const id of [...new Set(rows.flatMap(r=>r.item.existingClaimIds))].sort()){
  if(provenance.some(p=>p.inheritedClaimId===id))continue;
  assert.ok(!/^claim\.(?:n1|n2|qbp2b|qf[23])/.test(id),'Do not inherit an unverified extension: '+id);
  const c=recorded.claims.find(c=>c.id===id);assert.ok(c,'Missing recorded claim: '+id);
  const claimId='claim.n3r2.'+createHash('sha256').update(id).digest('hex').slice(0,12);
  claims.push({...c,...draft,id:claimId});
  provenance.push({claimId,inheritedClaimId:id,inheritedContentVersion:c.contentVersion,inheritedLastCheckedOn:c.lastCheckedOn,
    localMappingCheckedOn:'2026-11-05',statementUnchanged:true,
    verificationBasis:'Exact reuse of the recorded independent atomic statement and original check/access dates; no retrieval or new verification.'});
}
const sourceIds=new Set(claims.flatMap(c=>c.sourceIds));
const sources=[...sourceIds].map(id=>{
  const prior=old.QUESTION_NEW_N3_SOURCES.find(s=>s.id===id);
  const recordedSource=recorded.sources.find(s=>s.id===id);assert.ok(prior||recordedSource,id);
  const s=prior??{...recordedSource,...draft};
  // Bibliographic/rights metadata is unchanged; backlink IDs are expanded only.
  return {...s,evidenceClaimIds:claims.filter(c=>c.sourceIds.includes(id)).map(c=>c.id)};
});
for(const s of sources)for(const field of ['completeCitation','organizationOrJournal','accessedOn','sourceClass','licenseLabel','reuseStatus','usageRole','authorityAssessment'])assert.ok(s[field],s.id+' '+field);
const body='// Generated by tools/question-new-n3-round2/build-evidence.mjs from recorded offline metadata.\n'+
  '// First-round claims are exact; source clinical/rights metadata is unchanged. Only evidence backlinks expand.\n'+
  'import type {ClinicalSource,EvidenceClaim} from "./pilot-schema";\n\n'+
  'export const QUESTION_NEW_N3_ROUND2_CLAIM_PROVENANCE = '+JSON.stringify(provenance,null,2)+' as const;\n\n'+
  'export const QUESTION_NEW_N3_ROUND2_CLAIMS:EvidenceClaim[] = '+JSON.stringify(claims,null,2)+';\n\n'+
  'export const QUESTION_NEW_N3_ROUND2_SOURCES:ClinicalSource[] = '+JSON.stringify(sources,null,2)+';\n';
fs.writeFileSync('packages/clinical-content/src/question-new-n3-round2-evidence-20261105.ts',body);
console.log(JSON.stringify({revisions:rows.length,retainedClaims:old.QUESTION_NEW_N3_CLAIMS.length,claims:claims.length,sources:sources.length,newRetrievals:0}));
